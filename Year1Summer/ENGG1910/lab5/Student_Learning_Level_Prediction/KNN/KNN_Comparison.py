import numpy as np
import pandas as pd
import csv
import matplotlib.pyplot as plt
import random
import math
from sklearn import preprocessing
import pickle
from sklearn import datasets
from sklearn.model_selection import train_test_split
from sklearn.neighbors import KNeighborsClassifier
from sklearn.metrics import confusion_matrix
def KNN_comparison(train_data,test_number,k):
# Importing the dataset
  dataset = pd.read_csv('train_data.csv')
#looking at the first 5 values of the dataset
  dataset.head()
#Spliting the dataset in independent and dependent variables
  X = dataset.iloc[:train_data,1:7]
  # print(np.shape(X))
  y = dataset.iloc[:train_data,7].values
  # print(np.shape(y))
# Splitting the dataset into the Training set and Test set
  X_train, X_test, y_train, y_test = train_test_split(X, y, test_size = test_number, random_state = 0)

  knn=KNeighborsClassifier(n_neighbors=k)
  knn.fit(X_train, y_train)

  with open('KNN.pickle', 'wb') as model_file:
    pickle.dump(knn, model_file)
# Predicting the Test set results
  y_pred = knn.predict(X_test)
# Making the Confusion Matrix
  cm = confusion_matrix(y_test, y_pred)

#finding accuracy from the confusion matrix.
  a = cm.shape
  corrPred = 0
  falsePred = 0

  for row in range(a[0]):
      for c in range(a[1]):
          if row == c:
              corrPred +=cm[row,c]
          else:
              falsePred += cm[row,c]

  return corrPred/(cm.sum())

