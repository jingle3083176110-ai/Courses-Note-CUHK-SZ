    def train(self, patterns, iterations=10000, N=0.05, M=0.01, epoch=50, minn_batch=64):
        # N: learning rate
        # M: momentum factor
        for i in range(iterations):
            error = 0.0
            for p in patterns:
                inputs = p[0]
                targets = p[1]
                self.update(inputs)
                error = error + self.backPropagate(targets, N, M)
