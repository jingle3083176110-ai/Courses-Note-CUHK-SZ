# SVC Classification
# Importing the libraries
import numpy as np
import matplotlib.pyplot as plt
import matplotlib.image as mpimg
import pandas as pd
import pickle
from sklearn.metrics import confusion_matrix
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.svm import SVC
def SVC_Linear_comparison(train_data,test_number):
# Importing the dataset
  dataset = pd.read_csv('train_data.csv')
#Spliting the dataset in independent and dependent variables
  X = dataset.iloc[:train_data,1:7]
  # print(np.shape(X))
  y = dataset.iloc[:train_data,7].values
  # print(np.shape(y))
# Splitting the dataset into the Training set and Test set
  X_train, X_test, y_train, y_test = train_test_split(X, y, test_size = test_number, random_state = 82)
# Feature Scaling to bring the variable in a single scale
  sc = StandardScaler()
  X_train = sc.fit_transform(X_train)
  X_test = sc.transform(X_test)
# Fitting SVC Classification to the Training set with linear kernel
  svcclassifier = SVC(kernel = 'linear', random_state = 0)
  svcclassifier.fit(X_train, y_train)
  with open('linear.pickle', 'wb') as model_file:
    pickle.dump(svcclassifier, model_file)
# Predicting the Test set results
  y_pred = svcclassifier.predict(X_test)
  cm = confusion_matrix(y_test, y_pred)
#finding accuracy from the confusion matrix.
  a = cm.shape
  corrPred = 0
  falsePred = 0
  for row in range(a[0]):
      for c in range(a[1]):
          if row == c:
              corrPred +=cm[row,c]
          else:
              falsePred += cm[row,c]
  kernelLinearAccuracy = corrPred/(cm.sum())
  return corrPred/(cm.sum())
# SVC_Linear_model()

