# Naive Bayes Classification

# Importing the libraries
import numpy as np
import matplotlib.pyplot as plt
import matplotlib.image as mpimg
import pandas as pd
import csv
import random
import math
from sklearn.metrics import confusion_matrix
from sklearn.model_selection import train_test_split
import pickle
from sklearn.naive_bayes import GaussianNB

def NB_comparison(train_data,test_number):
# Importing the dataset
  dataset = pd.read_csv('train_data.csv')
#Spliting the dataset in independent and dependent variables
  X = dataset.iloc[:train_data,1:7]
  # print(np.shape(X))
  y = dataset.iloc[:train_data,7].values
  # print(np.shape(y))
# Splitting the dataset into the Training set and Test set
  X_train, X_test, y_train, y_test = train_test_split(X, y, test_size = test_number, random_state = 0)
# Fitting Naive Bayes Classification to the Training set
  nvclassifier = GaussianNB()
  nvclassifier.fit(X_train, y_train)

  with open('NB.pickle', 'wb') as model_file:
    pickle.dump(nvclassifier, model_file)
  y_pred = nvclassifier.predict(X_test)
# Making the Confusion Matrix
  cm = confusion_matrix(y_test, y_pred)
#finding accuracy from the confusion matrix.
  a = cm.shape
  corrPred = 0
  falsePred = 0
  for row in range(a[0]):
      for c in range(a[1]):
          if row == c:
              corrPred +=cm[row,c]
          else:
              falsePred += cm[row,c]

  return corrPred/(cm.sum())

